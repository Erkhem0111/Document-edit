// ─── Танилцуулгын агуулга ────────────────────────────────────────────────────
// Алхам бүр нэг товч/хэсгийг гэрэлтүүлж, энгийн үгээр тайлбарлана.
// target — элементийн data-tour нэр. Байхгүй бол дэлгэцийн голд гарна.
// mobile — утсан дээр өөр элемент/тайлбар (хажуугийн цэс ☰ дотор нуугддаг).
// Дэлгэцэнд харагдахгүй байгаа элементтэй алхмыг автоматаар алгасна
// (жишээ нь админ биш хүнд "Хэрэглэгчид").

export type TourId = "home" | "project" | "document";

export type TourStep = {
  target?: string;
  title: string;
  body: string;
  mobile?: { target?: string; body?: string; skip?: boolean };
};

export type TourContext = {
  firstName: string;
  isAdmin: boolean;
  isPending: boolean;
};

export function buildTour(id: TourId, ctx: TourContext): TourStep[] {
  if (id === "home") return homeTour(ctx);
  if (id === "project") return projectTour();
  return documentTour();
}

